const MEAT_FROZEN_NOTE = '冷凍のまま入れると加熱時間が延びることがある。前日に冷蔵庫へ移して解凍する'

const meat = (name: string, unit: string, units: [string, number][], extra: Partial<Seed> = {}): Seed => ({
  name,
  category: 'meat',
  unit,
  canFreeze: true,
  fridgeDays: 2,
  freezerDays: 30,
  defaultLocation: 'fridge',
  frozenCookNote: MEAT_FROZEN_NOTE,
  packageUnits: units.map(([label, quantity], i) => ({ label, quantity, isDefault: i === 0 })),
  ...extra,
})

const fish = (name: string, unit: string, units: [string, number][], extra: Partial<Seed> = {}): Seed => ({
  ...meat(name, unit, units, extra),
  category: 'fish',
})

const seasoning = (name: string, unit: 'g' | 'ml', extra: Partial<Seed> = {}): Seed => ({
  name,
  category: 'seasoning',
  unit,
  canFreeze: false,
  fridgeDays: 180,
  pantryDays: 180,
  defaultLocation: 'pantry',
  isStaple: true,
  ...extra,
})

const pkgs = (units: [string, number][]) =>
  units.map(([label, quantity], i) => ({ label, quantity, isDefault: i === 0 }))

