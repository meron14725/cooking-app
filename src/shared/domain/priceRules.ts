const norm = (s: string) => s.normalize('NFKC').trim()

/** 辞書の単位を食材の基準単位に直した量。直せなければ null */
function baseQuantity(rule: PriceRule, ing: { unit: string; gramsPerUnit: number | null }): number | null {
  const unit = norm(ing.unit)
  if (unit === rule.unit) return rule.quantity
  if (rule.unit === 'g' && ing.gramsPerUnit) return rule.quantity / ing.gramsPerUnit
  if (unit === 'g' && rule.unit === 'kg') return rule.quantity * 1000
  return null
}

export type PriceRuleInput = {
  name: string
  aliases: string[]
  unit: string
  gramsPerUnit: number | null
  packageUnits: { quantity: number; isDefault: boolean }[]
}

/**
 * 名前から代表量あたりの価格（円）を決める。辞書に当たらないか、単位を直せなければ null（AI に回す）
 */
export function priceByRule(ing: PriceRuleInput): number | null {
  const names = [ing.name, ...ing.aliases].map(norm)
  const rule = PRICE_RULES.find((x) => names.some((n) => x.pattern.test(n)))
  if (!rule) return null
  const base = baseQuantity(rule, ing)
  if (base === null || base <= 0) return null
  const price = (rule.yen / base) * representativeQuantity(ing)
  return Math.max(1, Math.round(price))
}
